"""Which directories need their own node_modules -- detected, not assumed.

2026-09-22: a project made of three standalone apps (backend/, frontend/,
admin/, no workspaces tying them together) had no nodeModulesDirs configured.
Onboarding had only understood `workspaces`, and the project's layout arrived
AFTER it was onboarded anyway. The review service installed at a root with no
dependencies, every check in every app failed on a missing tool, the base
failed identically, and every commit came back READY having run nothing.

Two detectors exist on purpose -- provisioning (Python) records it at
onboarding so it is visible, the reviewer (JavaScript) re-reads the tree at
review time so a project that grows a package is not stuck with a snapshot.
Two implementations of one rule drift. This runs every layout through BOTH and
requires the same answer.
"""
import json
import subprocess
from pathlib import Path

import pytest

from agent import paths
from agent.provisioning import _read_json, _workspace_dirs

REVIEWER = paths.REPO_ROOT / "services" / "commit-reviewer" / "reviewer.js"


def _pkg(d: Path, **fields):
    d.mkdir(parents=True, exist_ok=True)
    (d / "package.json").write_text(json.dumps({"name": d.name or "root", **fields}))


def python_detects(root: Path) -> list[str]:
    return sorted(_workspace_dirs(root, _read_json(root / "package.json")))


def js_detects(root: Path) -> list[str]:
    out = subprocess.run(
        ["node", "-e", f"const r=require({json.dumps(str(REVIEWER))});"
                       f"console.log(JSON.stringify(r.detectNodeModulesDirs({json.dumps(str(root))})))"],
        capture_output=True, text=True, timeout=60, cwd=str(REVIEWER.parent))
    assert out.returncode == 0, out.stderr
    # The reviewer logs on require; the JSON is the last line.
    return sorted(json.loads(out.stdout.strip().splitlines()[-1]))


# (name, builder, expected) -- expected is what BOTH must say.
def standalone_apps(r):
    _pkg(r, scripts={"test": "npm --prefix backend test"})          # task runner, no deps
    _pkg(r / "backend", dependencies={"express": "1"})
    _pkg(r / "frontend", devDependencies={"vite": "1"})
    _pkg(r / "admin", devDependencies={"vite": "1"})


def pnpm_monorepo(r):
    _pkg(r)                                                          # declares nothing...
    (r / "pnpm-workspace.yaml").write_text("packages:\n  - 'apps/*'\n")
    _pkg(r / "apps" / "api", dependencies={"a": "1"})
    _pkg(r / "apps" / "web", dependencies={"b": "1"})


def npm_workspaces(r):
    _pkg(r, workspaces=["packages/*"])
    _pkg(r / "packages" / "core", dependencies={"a": "1"})


def single_package(r):
    _pkg(r, dependencies={"express": "1"})


def root_with_nothing(r):
    _pkg(r, scripts={"x": "echo"})


def copies_in_output_dirs(r):
    _pkg(r, dependencies={"a": "1"})
    _pkg(r / "node_modules" / "lodash", dependencies={"x": "1"})
    _pkg(r / "dist" / "bundle", dependencies={"x": "1"})


def too_deep(r):
    _pkg(r, dependencies={"a": "1"})
    _pkg(r / "a" / "b" / "c", dependencies={"x": "1"})             # depth 3


LAYOUTS = [
    ("standalone apps, no workspaces", standalone_apps, ["admin", "backend", "frontend"]),
    ("pnpm workspace root", pnpm_monorepo, [".", "apps/api", "apps/web"]),
    ("npm workspaces field", npm_workspaces, [".", "packages/core"]),
    ("single package", single_package, ["."]),
    ("a root that needs nothing", root_with_nothing, []),
    ("package.json copies in output dirs", copies_in_output_dirs, ["."]),
    ("a package too deep to walk to", too_deep, ["."]),
]


@pytest.mark.parametrize("name,build,expected", LAYOUTS, ids=[x[0] for x in LAYOUTS])
def test_both_detectors_give_the_same_answer(tmp_path, name, build, expected):
    build(tmp_path)
    assert python_detects(tmp_path) == expected, "provisioning disagrees with the expected layout"
    assert js_detects(tmp_path) == expected, "the reviewer disagrees with the expected layout"


def test_the_case_that_broke_is_covered_by_both():
    """Named separately so a regression points at the incident, not a table row."""
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        root = Path(d)
        standalone_apps(root)
        assert python_detects(root) == js_detects(root) == ["admin", "backend", "frontend"]


# --- the reviewer's use of it ---------------------------------------------

def _reviewer(expr: str, env: dict | None = None) -> str:
    import os
    out = subprocess.run(["node", "-e", f"const r=require({json.dumps(str(REVIEWER))});{expr}"],
                         capture_output=True, text=True, timeout=60, cwd=str(REVIEWER.parent),
                         env={**os.environ, **(env or {})})
    assert out.returncode == 0, out.stderr
    return out.stdout.strip().splitlines()[-1]


def _projects_json(tmp_path, entries: dict) -> Path:
    pj = tmp_path / "projects.json"
    pj.write_text(json.dumps({"projects": entries}))
    return pj


def test_an_unconfigured_project_gets_what_the_tree_has(tmp_path):
    live = tmp_path / "proj"
    standalone_apps(live)
    pj = _projects_json(tmp_path, {"p": {"live": str(live), "sandbox": str(live), "review": {"checks": []}}})
    out = _reviewer("console.log(JSON.stringify(r.currentProjects().p.nodeModulesDirs))",
                    {"AGENT_PROJECTS_JSON": str(pj), "REVIEW_ONLY_PROJECTS_JSON": "1"})
    assert sorted(json.loads(out)) == ["admin", "backend", "frontend"]


def test_a_configured_list_is_a_floor_not_a_ceiling(tmp_path):
    """The staleness this exists to prevent: a project onboarded with the
    right list, which then grows another package."""
    live = tmp_path / "proj"
    standalone_apps(live)
    pj = _projects_json(tmp_path, {"p": {
        "live": str(live), "sandbox": str(live),
        "review": {"checks": [], "nodeModulesDirs": ["backend"]}}})
    out = _reviewer("console.log(JSON.stringify(r.currentProjects().p.nodeModulesDirs))",
                    {"AGENT_PROJECTS_JSON": str(pj), "REVIEW_ONLY_PROJECTS_JSON": "1"})
    dirs = json.loads(out)
    assert dirs[0] == "backend", "a configured entry was dropped or reordered"
    assert sorted(dirs) == ["admin", "backend", "frontend"]


def test_an_explicit_empty_list_is_honoured(tmp_path):
    """[] is a decision -- "this project needs none" -- not an absence."""
    live = tmp_path / "proj"
    standalone_apps(live)
    pj = _projects_json(tmp_path, {"p": {
        "live": str(live), "sandbox": str(live),
        "review": {"checks": [], "nodeModulesDirs": []}}})
    out = _reviewer("console.log(JSON.stringify(r.currentProjects().p.nodeModulesDirs))",
                    {"AGENT_PROJECTS_JSON": str(pj), "REVIEW_ONLY_PROJECTS_JSON": "1"})
    assert json.loads(out) == []
